/** A food's icon (cutlery when it has none). */
export function FoodIcon({
  icon,
  ...props
}: { icon: FoodIconKey | null } & Omit<LucideProps, "ref">) {
  const drawing = FOOD_ICONS[icon ?? "utensils"].drawing;
  if (Array.isArray(drawing)) return <Icon iconNode={drawing} aria-hidden {...props} />;
  const Drawn = drawing as LucideIcon;
  return <Drawn aria-hidden {...props} />;
}
